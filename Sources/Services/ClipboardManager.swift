import Foundation
import AppKit
import Vision
import ImageIO
import Combine

final class ClipboardManager: ObservableObject {
    @Published var entries: [ClipboardEntry] = []
    @Published var statusMessage: String?
    private var lastChangeCount = 0
    private var timer: Timer?
    private var cleanupTimer: Timer?
    private var settingsObserver: AnyCancellable?
    private let pasteboard: NSPasteboard
    private let storage: StorageManager
    private let ocrQueue = DispatchQueue(label: "com.iclippy.ocr", qos: .utility)
    private var pendingOCR = Set<UUID>()
    private let settings: AppSettings
    static let maxItemBytes = 10 * 1024 * 1024
    static let privacyTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]

    init(pasteboard: NSPasteboard = .general, storage: StorageManager = .shared, settings: AppSettings = .shared, monitoring: Bool = true) {
        self.pasteboard = pasteboard
        self.storage = storage
        self.settings = settings
        entries = storage.loadHistory()
        statusMessage = storage.loadError
        lastChangeCount = pasteboard.changeCount
        cleanup()
        if monitoring { startMonitoring() }
        cleanupTimer = Timer.scheduledTimer(withTimeInterval: 60, repeats: true) { [weak self] _ in self?.cleanup() }
        settingsObserver = settings.objectWillChange.sink { [weak self] _ in
            self?.lastChangeCount = self?.pasteboard.changeCount ?? 0
            DispatchQueue.main.async { self?.cleanup(); self?.indexImages() }
        }
        indexImages()
    }

    func startMonitoring() {
        timer?.invalidate()
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.checkClipboard() }
    }
    func stopMonitoring() { timer?.invalidate(); timer = nil }

    func checkClipboard() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        let app = NSWorkspace.shared.frontmostApplication
        guard !settings.privateMode, !settings.excludes(app?.bundleIdentifier),
              !Self.privacyTypes.contains(where: { pasteboard.types?.contains(NSPasteboard.PasteboardType($0)) == true }) else { return }
        var entry: ClipboardEntry?
        if let data = pasteboard.data(forType: .tiff) ?? pasteboard.data(forType: .png) {
            entry = .fromImage(data)
        } else if let text = pasteboard.string(forType: .string), !text.isEmpty {
            let rtf = pasteboard.data(forType: .rtf)
            entry = .fromText(text, hasRTF: rtf != nil, rtfData: rtf)
        }
        guard var captured = entry else { return }
        captured.sourceAppName = app?.localizedName
        captured.sourceBundleID = app?.bundleIdentifier
        guard captured.content.utf8.count + (captured.imageData?.count ?? 0) + (captured.rtfData?.count ?? 0) <= Self.maxItemBytes else {
            statusMessage = "An item larger than 10 MB was skipped."; return
        }
        // Compare with the latest ordinary capture; pinned sorting does not affect deduplication.
        if let latest = entries.filter({ !$0.isSnippet }).max(by: { $0.timestamp < $1.timestamp }),
           latest.content == captured.content, latest.imageData == captured.imageData,
           latest.rtfData == captured.rtfData, latest.type == captured.type { return }
        entries.append(captured)
        cleanup()
        indexImages()
    }

    func copyToClipboard(_ entry: ClipboardEntry, plainText: Bool = false) {
        pasteboard.clearContents()
        if let imageData = entry.imageData, entry.type == .image {
            if plainText {
                pasteboard.setString(entry.recognizedText ?? "", forType: .string)
            } else if let image = NSImage(data: imageData) { pasteboard.writeObjects([image]) }
        } else if let rtf = entry.rtfData, !plainText {
            pasteboard.setData(rtf, forType: .rtf)
            pasteboard.setString(entry.content, forType: .string)
        } else { pasteboard.setString(entry.content, forType: .string) }
        // Record exactly our write, rather than skipping an unrelated later clipboard change.
        lastChangeCount = pasteboard.changeCount
    }

    func togglePin(_ entry: ClipboardEntry) {
        guard let index = entries.firstIndex(where: { $0.id == entry.id }) else { return }
        entries[index].isPinned.toggle(); cleanup()
    }
    func deleteEntry(_ entry: ClipboardEntry) { entries.removeAll { $0.id == entry.id }; persist() }
    func clearUnpinned() { entries.removeAll { !$0.isPinned && !$0.isSnippet }; persist() }
    func saveSnippet(name: String, text: String, replacing id: UUID? = nil) {
        let name = name.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !name.isEmpty, !text.isEmpty, text.utf8.count <= Self.maxItemBytes else { return }
        if let index = entries.firstIndex(where: { $0.id == id }) {
            entries[index].snippetName = name; entries[index].content = text
            entries[index].rtfData = nil; entries[index].type = ContentType.detect(from: text)
        } else {
            var entry = ClipboardEntry.fromText(text)
            entry.snippetName = name; entries.append(entry)
        }
        cleanup()
    }
    func cleanup() {
        entries = HistoryPolicy.trim(entries, days: settings.retentionDays,
            count: settings.maxEntries, bytes: settings.maxStorageMB * 1024 * 1024)
        persist()
    }
    private func persist() {
        storage.saveHistory(entries) { [weak self] success in
            if !success { self?.statusMessage = "History could not be saved. Check disk space and Keychain access." }
        }
    }
    func indexImages() {
        guard settings.recognizeImages else { return }
        for entry in entries where entry.type == .image && entry.recognizedText == nil && !pendingOCR.contains(entry.id) {
            guard let data = entry.imageData else { continue }
            pendingOCR.insert(entry.id)
            ocrQueue.async { [weak self] in
                let text = ImageTextRecognizer.recognize(data)
                DispatchQueue.main.async {
                    guard let self else { return }
                    self.pendingOCR.remove(entry.id)
                    guard self.settings.recognizeImages, let text,
                          let index = self.entries.firstIndex(where: { $0.id == entry.id }) else { return }
                    self.entries[index].recognizedText = text
                    self.persist()
                }
            }
        }
    }
    deinit { timer?.invalidate(); cleanupTimer?.invalidate() }
}
